PRODUCTION_PHRASES = {
    "давящая боль за грудиной, отдаёт в левую руку, холодный пот",
    "самая сильная головная боль в жизни, как удар по голове",
    "шею не могу нагнуть, от света больно глазам, температура 39",
    "год назад болело в груди, обследовалась, всё прошло, сейчас насморк",
}


def build() -> dict[str, object]:
    items: list[dict[str, object]] = []
    sequence = 0
    for code, groups in SEEDS.items():
        for group_name in (
            "ru_positive",
            "kk_positive",
            "ru_negative",
            "kk_negative",
        ):
            language, polarity = group_name.split("_")
            for phrase in groups[group_name]:
                sequence += 1
                is_positive = polarity == "positive"
                is_production = phrase in PRODUCTION_PHRASES
                items.append(
                    {
                        "id": f"rf-{sequence:03d}",
                        "language": language,
                        "messages": [{"role": "user", "content": phrase}],
                        "expected_emergency": is_positive,
                        "expected_codes": [code] if is_positive else [],
                        "target_trigger": code,
                        "trap": None if is_positive else "negation_history_or_ownership",
                        "provenance": {
                            "kind": (
                                "production_regression"
                                if is_production
                                else "synthetic_adversarial"
                            ),
                            "source": (
                                "manual production-task reproduction 2026-09-26"
                                if is_production
                                else "authored from the eight-rule taxonomy for this benchmark"
                            ),
                            "clinician_validated": False,
                            "validation_status": "pending",
                        },
                    }
                )

    return {
        "schema_version": "redflags-eval-v1",
        "frozen_on": "2026-09-26",
        "research_only": True,
        "label_scope": "binary emergency plus expected rule code",
        "limitations": [
            "Synthetic items are not an independent clinical gold set.",
            "Labels follow the existing eight-rule taxonomy and await clinician review.",
            "Only four verbatim items come from the 2026-09-26 production-task reproduction.",
        ],
        "items": items,
    }


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        json.dumps(build(), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUTPUT} ({len(build()['items'])} items)")


if __name__ == "__main__":
    main()
